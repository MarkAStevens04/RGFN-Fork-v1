#!/bin/bash
#SBATCH --job-name=dock6td3m
#SBATCH --nodes=1
#SBATCH --gpus-per-node=4
#SBATCH --ntasks=64
#SBATCH --chdir=/scratch/markymoo/rgfn_runs
#SBATCH --output=dock6td3m-%j.out
#SBATCH --error=dock6td3m-%j.err

# 6TD3 gate RE-CALIBRATION against PROPERTY-MATCHED decoys.
#
# WHY. The 6TD3 hit gate (-2.0) rests on a decoy set that is WARHEAD-matched, not property-matched:
# every decoy keeps the CR8-like purine, but molecular weight is only range-bounded (250-650) and no
# other property is matched. That controls for "the oracle just reads ATP-pocket binding" -- a real
# and hard control -- but NOT for "the oracle just reads gross physicochemistry". Entry 007 showed
# the size confound is large on this system (knowns ~93 Da heavier; the differential survives MW
# matching at 0.95->0.87 where absolute Tier-2 collapses 0.89->0.65), which is exactly why the
# remaining property axes need closing rather than assuming.
#
# The new negative set is DUD-E style: matched on MW / logP / HBD / HBA / rotatable bonds / formal
# charge, and topologically DISTINCT (ECFP4 Tanimoto < 0.35 to every active). Generated by the shared
# `docking_clpp/make_matched_decoys.py` -- the same machinery behind ClpP's AUROC 0.895 calibration --
# from the cached target-agnostic ChEMBL background pool, so no internet is needed.
# Match quality: actives MW 436 / logP 3.95, decoys MW 440 / logP 3.57.
#
# BOTH SETS ARE RE-DOCKED IN ONE JOB, deliberately. The actives already have scores from job 69271
# (June), but re-docking them here means actives and decoys are scored under identical gnina /
# receptor / exhaustiveness conditions in a single run, so nothing in the AUROC can be attributed to
# drift between two docking campaigns. It also reproduces the published 0.946 as a side-effect check.
#
# Outputs land in $OUTDIR on scratch -- the committed `decoy_cdk_results.csv` (warhead-matched) is
# NOT overwritten, so both negative sets remain comparable side by side.
#
# SMOKE:  MAX=3 sbatch -p debug_full_node --time=00:20:00 <this>
# FULL :  sbatch -p debug_full_node --time=01:00:00 <this>
set -euo pipefail

REPO=/home/markymoo/projects/RGFN_Fork/RGFN-Fork
DOCK=$REPO/experiments/oracle_validation/docking_6td3
export OUTDIR=${OUTDIR:-$SCRATCH/rgfn_runs/dock_6td3_matched_${SLURM_JOB_ID}}
export WORK=${WORK:-$SCRATCH/dock_6td3_matched_${SLURM_JOB_ID}}
export N_GPU=${N_GPU:-4}
export PROCS_PER_GPU=${PROCS_PER_GPU:-4}
# THE POINT OF THIS SCRIPT: the property-matched negative set instead of the warhead-matched one.
export DECOY_SMI=${DECOY_SMI:-$DOCK/decoys_matched.smiles}
mkdir -p "$OUTDIR" "$WORK"

source /home/markymoo/miniconda3/etc/profile.d/conda.sh
conda activate rgfn          # RDKit only; gnina loads its own CUDA-12 via run_gnina.sh

echo "node=$(hostname)  gpus=${CUDA_VISIBLE_DEVICES:-?}  cpus=${SLURM_CPUS_ON_NODE:-?}"
echo "DECOY_SMI=$DECOY_SMI"
echo "OUTDIR=$OUTDIR"
nvidia-smi -L

python "$DOCK/dock_cluster.py"
echo "results in $OUTDIR"

# Verdicts that produce a copy. `resample` is deliberately included: the cell's POOL is missing but
# its checkpoints and trace are intact, so everything except candidates/ travels now and the pool is
# regenerated by sampling the frozen policy -- minutes, against the GPU-days a re-train would cost.
COPYABLE = {"copy", "attention", "resample"}

# What a training cell consists of. Anything not listed is left behind on purpose: `fixed_reward/`
# (post-Stage-2, superseded by the snapshot), tb_logs, and the generator's own scratch.
#
# TWO TANGO EXCLUSIONS, AND THEY ARE NOT THE SAME DECISION:
#   syntheseus_results/  4.1 GB/cell. ARM 1 -- the in-loop route dumps, keyed by oracle call. The
#                        project RETIRED this arm: its coverage correlates with the generator's own
#                        mode collapse (7 of 218 molecules on the pruned sEH pool), so it cannot even
